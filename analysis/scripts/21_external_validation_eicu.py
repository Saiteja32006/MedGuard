# PART 2 — coverage transfer, per hospital
# ============================================================================

def part2_coverage(out_dir, pat, med, lab, expanded):
    print("=" * 74)
    print("PART 2 — COVERAGE TRANSFER (metrics A/B/C on eICU, per hospital)")
    print("=" * 74)

    ing2rules = defaultdict(list)
    for e in expanded:
        ing2rules[e["ingredient"]].append(e["rule_id"])
    ingredients = set(ing2rules)

    m = med.copy()
    m["drug_norm"] = [normalize_drug(d) for d in m["drugname"].values]
    ings, rids = [], []
    for nm in m["drug_norm"].values:
        hit = drug_tokens(nm) & ingredients
        if hit:
            i = sorted(hit)[0]
            ings.append(i)
            rids.append("|".join(sorted(set(ing2rules[i]))))
        else:
            ings.append("")
            rids.append("")
    m["ingredient"] = ings
    m["rule_ids"] = rids
    m = m.merge(pat[["patientunitstayid", "hospitalid"]],
                on="patientunitstayid", how="left")

    lab_idx = defaultdict(list)
    for sid, lb, off, val in lab[["patientunitstayid", "lab", "labresultoffset",
                                  "labresult"]].itertuples(index=False):
        lab_idx[(sid, lb)].append((off, val))

    rule_lab = {}
    for e in expanded:
        raw = (e.get("lab_name") or "").strip()
        if not raw:
            rule_lab[e["rule_id"]] = "__CATEGORICAL__"
        else:
            # eICU has no eGFR series; eGFR rules resolve to creatinine here.
            rule_lab[e["rule_id"]] = cov20.canon_lab(raw)

    scoped = m[m["ingredient"] != ""].copy()
    evaluable = []
    for sid, rl, off in scoped[["patientunitstayid", "rule_ids",
                                "drugstartoffset"]].itertuples(index=False):
        need = None
        for rid in rl.split("|"):
            need = rule_lab.get(rid)
            if need:
                break
        if need == "__CATEGORICAL__":
            evaluable.append(True)
        elif not need:
            evaluable.append(False)
        else:
            hits = lab_idx.get((sid, need), ())
            evaluable.append(any(abs(o - off) <= WINDOW_MIN for o, _ in hits))
    scoped["evaluable"] = evaluable

    A = len(scoped) / max(len(m), 1)
    B = scoped["evaluable"].mean() if len(scoped) else 0.0
    C = 1.0 - (int(scoped["evaluable"].sum()) / max(len(m), 1))

    print(f"  orders analysed              : {len(m):,}")
    print(f"  A  applicability             : {A:.2%}")
    print(f"  B  evaluable | in scope      : {B:.2%}")
    print(f"  C  silent pass-through       : {C:.2%}")
    print()

    ph = m.groupby("hospitalid").size().rename("orders").to_frame()
    ph["in_scope"] = scoped.groupby("hospitalid").size()
    ph["evaluable"] = scoped[scoped["evaluable"]].groupby("hospitalid").size()
    ph = ph.fillna(0)
    ph = ph[ph["orders"] >= 200]
    ph["A"] = ph["in_scope"] / ph["orders"]
    ph["C"] = 1.0 - ph["evaluable"] / ph["orders"]
    ph.to_csv(out_dir / "p2_coverage_by_hospital.csv")

    if len(ph):
        print(f"  PER-HOSPITAL applicability (n={len(ph)} hospitals >=200 orders):")
        print(f"    min {ph['A'].min():.2%} | median {ph['A'].median():.2%} | "
              f"max {ph['A'].max():.2%}  (spread {ph['A'].max()-ph['A'].min():.1%})")
        print(f"  PER-HOSPITAL silent pass-through:")
        print(f"    min {ph['C'].min():.2%} | median {ph['C'].median():.2%} | "
              f"max {ph['C'].max():.2%}")
        print("    ^ if this spread is wide, scope is institution-dependent and")
        print("      a single coverage figure understates the variability.")
        print()

    return {"A_applicability": round(float(A), 6),
            "B_evaluable": round(float(B), 6),
            "C_silent_passthrough": round(float(C), 6),
            "n_hospitals": int(len(ph)),
            "A_min": round(float(ph["A"].min()), 6) if len(ph) else None,
            "A_median": round(float(ph["A"].median()), 6) if len(ph) else None,
            "A_max": round(float(ph["A"].max()), 6) if len(ph) else None}


