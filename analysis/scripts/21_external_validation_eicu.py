def map_allergy(name):
    """eICU allergyname free text -> class key, or None."""
    if not isinstance(name, str) or not name.strip():
        return None
    x = name.lower().strip()
    if x in ALLERGY_ALIASES:
        return ALLERGY_ALIASES[x]
    if x in ALLERGY_CLASSES:
        return x
    for alias, cls in ALLERGY_ALIASES.items():
        if alias in x:
            return cls
    for cls in ALLERGY_CLASSES:
        if cls in x:
            return cls
    return None


