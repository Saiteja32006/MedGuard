def load_eicu(eicu_dir, out_dir):
    """Load and cache the five eICU tables we need."""
    ck = out_dir / "eicu_cache.parquet"
    eicu_dir = Path(eicu_dir)

    def rd(name, usecols):
        for cand in (eicu_dir / f"{name}.csv.gz", eicu_dir / f"{name}.csv"):
            if cand.exists():
                print(f"    reading {cand.name}")
                return pd.read_csv(cand, usecols=usecols, low_memory=False)
        sys.exit(f"FATAL: {name}.csv[.gz] not found in {eicu_dir}")

    print("  loading eICU tables...")
    pat = rd("patient", ["patientunitstayid", "hospitalid", "gender", "age",
                         "unittype"])
    med = rd("medication", ["patientunitstayid", "drugname", "dosage",
                            "routeadmin", "drugstartoffset",
                            "drugordercancelled"])
    lab = rd("lab", ["patientunitstayid", "labname", "labresult",
                     "labresultoffset"])
    alg = rd("allergy", ["patientunitstayid", "allergyname", "allergytype",
                         "allergyoffset"])

    med = med[med["drugordercancelled"].astype(str).str.lower() != "yes"]
    med = med.dropna(subset=["drugname", "drugstartoffset"])
    lab = lab[lab["labname"].isin(EICU_LABMAP)].dropna(subset=["labresult"])
    lab["lab"] = lab["labname"].map(EICU_LABMAP)
    for lb, factor in UNIT_RESCALE.items():
        m = lab["lab"] == lb
        lab.loc[m, "labresult"] = lab.loc[m, "labresult"] * factor

    alg = alg[alg["allergytype"].astype(str).str.lower().str.contains("drug",
                                                                      na=False)]
    alg["allergy_class"] = alg["allergyname"].map(map_allergy)

    print(f"    patients {len(pat):,} | meds {len(med):,} | "
          f"labs {len(lab):,} | drug allergies {len(alg):,}")
    print(f"    hospitals: {pat['hospitalid'].nunique()}")
    return pat, med, lab, alg


# ============================================================================
# PART 1 — non-circular allergy validation  (THE HEADLINE)
# ============================================================================

def part1_allergy(out_dir, pat, med, alg, rules):
    print("=" * 74)
    print("PART 1 — INDEPENDENT-LABEL VALIDATION VIA eICU ALLERGY TABLE")
    print("=" * 74)
    print("  Labels here come from clinician-entered allergy records, NOT from")
    print("  our rule set. This is the non-circular part of the experiment.")
    print()

    # Which allergy classes does MedGuard's categorical rule set actually cover?
    covered = set()
    for r in rules:
        cond = (r.get("conflict_condition") or "").lower()
        for cls in ALLERGY_CLASSES:
            if cls in cond or cls.rstrip("s") in cond:
                covered.add(cls)
        d = normalize_drug(r.get("drug", ""))
        for cls, members in ALLERGY_CLASSES.items():
            if d and d in members:
                covered.add(cls)
    print(f"  allergy classes covered by our rule set: {sorted(covered) or '(none detected)'}")
    print()

    alg2 = alg.dropna(subset=["allergy_class"])
    stay_allergies = defaultdict(set)
    stay_allergy_offset = {}
    for sid, cls, off in alg2[["patientunitstayid", "allergy_class",
                               "allergyoffset"]].itertuples(index=False):
        stay_allergies[sid].add(cls)
        stay_allergy_offset[(sid, cls)] = min(
            stay_allergy_offset.get((sid, cls), 10**9), off if pd.notna(off) else 10**9)

    print(f"  stays with >=1 mapped drug allergy: {len(stay_allergies):,}")

    med2 = med[med["patientunitstayid"].isin(stay_allergies)].copy()
    med2["drug_norm"] = [normalize_drug(d) for d in med2["drugname"].values]

    ing2cls = defaultdict(set)
    for cls, members in ALLERGY_CLASSES.items():
        for m in members:
            ing2cls[m].add(cls)

    rows = []
    for sid, dn, off in med2[["patientunitstayid", "drug_norm",
                              "drugstartoffset"]].itertuples(index=False):
        toks = drug_tokens(dn)
        hit_cls = set()
        for t in toks:
            hit_cls |= ing2cls.get(t, set())
        pat_alg = stay_allergies.get(sid, set())

        strict = hit_cls & pat_alg
        strict = {c for c in strict
                  if stay_allergy_offset.get((sid, c), 10**9) <= (off if pd.notna(off) else -10**9)}

        xreact = set()
        for a, b in CROSS_REACT.items():
            if a in pat_alg and b in hit_cls:
                if stay_allergy_offset.get((sid, a), 10**9) <= (off if pd.notna(off) else -10**9):
                    xreact.add(f"{a}->{b}")

        rows.append({
            "patientunitstayid": sid,
            "drug_norm": dn,
            "conflict_strict": bool(strict),
            "conflict_class": sorted(strict)[0] if strict else "",
            "cross_reactive": bool(xreact),
            "in_rule_scope": bool(strict & covered),
        })

    df = pd.DataFrame(rows).merge(
        pat[["patientunitstayid", "hospitalid"]], on="patientunitstayid", how="left")

    n_orders = len(df)
    n_conf = int(df["conflict_strict"].sum())
    n_in_scope = int(df["in_rule_scope"].sum())
    n_xr = int(df["cross_reactive"].sum())
    detect = n_in_scope / max(n_conf, 1)

    print(f"  orders in allergy-bearing stays        : {n_orders:,}")
    print(f"  GENUINE drug-allergy conflicts (strict): {n_conf:,}")
    print(f"    ...covered by our rule set           : {n_in_scope:,}  "
          f"({detect:.2%})   <-- EXTERNAL S1 DETECTION")
    print(f"    ...MISSED (outside rule scope)       : {n_conf - n_in_scope:,}")
    print(f"  cross-reactive (penicillin->ceph), reported separately: {n_xr:,}")
    print()

    miss = (df[df["conflict_strict"] & ~df["in_rule_scope"]]
            .groupby("conflict_class").size().sort_values(ascending=False))
    if len(miss):
        print("  Missed conflicts by allergy class (the coverage story, with real labels):")
        for cls, c in miss.items():
            print(f"    {cls:<20} {c:,}")
        print()

    per_hosp = (df[df["conflict_strict"]]
                .groupby("hospitalid")
                .agg(conflicts=("conflict_strict", "sum"),
                     covered=("in_rule_scope", "sum")))
    per_hosp["detection"] = per_hosp["covered"] / per_hosp["conflicts"].clip(lower=1)
    per_hosp = per_hosp[per_hosp["conflicts"] >= 10]

    if len(per_hosp):
        d = per_hosp["detection"]
        print(f"  PER-HOSPITAL detection (hospitals with >=10 conflicts, "
              f"n={len(per_hosp)}):")
        print(f"    min {d.min():.2%} | p25 {d.quantile(.25):.2%} | "
              f"median {d.median():.2%} | p75 {d.quantile(.75):.2%} | max {d.max():.2%}")
        print("    ^ THIS is the across-institution number oJaU asked for.")
        print()
    per_hosp.to_csv(out_dir / "p1_detection_by_hospital.csv")
    df.to_parquet(out_dir / "p1_allergy_orders.parquet", index=False)

    return {"n_orders": n_orders, "n_conflicts_strict": n_conf,
            "n_covered": n_in_scope, "external_S1_detection": round(detect, 6),
            "n_cross_reactive": n_xr,
            "per_hospital_detection_median":
                round(float(per_hosp["detection"].median()), 6) if len(per_hosp) else None,
            "per_hospital_detection_min":
                round(float(per_hosp["detection"].min()), 6) if len(per_hosp) else None,
            "per_hospital_detection_max":
                round(float(per_hosp["detection"].max()), 6) if len(per_hosp) else None,
            "n_hospitals_scored": int(len(per_hosp))}


