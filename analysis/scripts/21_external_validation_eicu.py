#!/usr/bin/env python3
"""
21_external_validation_eicu.py — External validation on eICU-CRD
=================================================================

Answers Reviewer oJaU's requested Experiment 2:
  "An external validation on a non-MIMIC dataset with different formulary
   conventions and lab reference ranges. The conformal guarantee is
   distribution-free in theory, but whether this holds in practice across
   institutions is another thing."

DESIGN NOTE — READ THIS BEFORE RUNNING
--------------------------------------
Rebuilding MedConflict-Bench on eICU with the same rule set would be CIRCULAR:
ground truth generated by the system under test. We do not do that.

Instead:

  PART 1 (non-circular, the headline)
    eICU has a structured `allergy` table -- clinician-entered, independent of
    our rule set. Joined against `medication`, it yields REAL drug-allergy
    conflicts with INDEPENDENT labels across 200+ hospitals. This is a genuine
    external test of stratum-1 detection.

  PART 2 (coverage transfer, no labels needed)
    Metrics A/B/C from the MIMIC coverage experiment, recomputed on eICU and
    broken down PER HOSPITAL. Answers "does scope hold across institutions."

  PART 3 (calibration transfer)
    tau_hat recalibrated on eICU vs transferred from MIMIC; per-hospital spread.
    Plus boundary-density shift: what fraction of orders sit near a decision
    threshold, per hospital. A3 showed all the risk concentrates at boundaries,
    so a shift in boundary density IS a shift in practical risk.

  WHAT WE DO NOT CLAIM
    Numerical-threshold DETECTION accuracy on eICU. There is no independent
    label source for it, and generating one from our own rules would be
    circular. State this explicitly in the paper.

REQUIREMENTS
------------
  eICU-CRD v2.0 from PhysioNet (separate DUA from MIMIC-IV).
  Files needed: patient.csv.gz, medication.csv.gz, lab.csv.gz,
                allergy.csv.gz, hospital.csv.gz
  Also needs 20_coverage_denominator.py in the SAME FOLDER (imports the
  drug normalizer and rule-set derivation, so the two experiments cannot drift).

USAGE
-----
  python 21_external_validation_eicu.py --stage all \
      --eicu-dir  /path/to/eicu-crd-2.0 \
      --bench-dir /path/to/folder/with/medconflict_bench_v2.jsonl \
      --out-dir   ./out/external

Author: Ala Sai Teja, IIIT Sricity — NeurIPS 2026 rebuttal
"""

