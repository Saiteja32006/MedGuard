def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", default="all", choices=["all", "1", "2", "3"])
    ap.add_argument("--eicu-dir", required=True)
    ap.add_argument("--bench-dir", required=True,
                    help="folder containing medconflict_bench_v2.jsonl")
    ap.add_argument("--out-dir", default="./out/external")
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    cov20.BENCH = Path(args.bench_dir)
    rules, expanded = cov20.stage0_rules(out_dir, verbose=True)

    pat, med, lab, alg = load_eicu(args.eicu_dir, out_dir)
    print()

    results = {"dataset": "eICU-CRD v2.0",
               "n_hospitals_total": int(pat["hospitalid"].nunique())}

    if args.stage in ("all", "1"):
        results["part1_allergy_validation"] = part1_allergy(out_dir, pat, med, alg, rules)
    if args.stage in ("all", "2"):
        results["part2_coverage"] = part2_coverage(out_dir, pat, med, lab, expanded)
    if args.stage in ("all", "3"):
        results["part3_boundaries"] = part3_boundaries(out_dir, pat, lab, rules)

    with open(out_dir / "external_validation_results.json", "w") as f:
        json.dump(results, f, indent=2, default=str)
    print(f"[saved] {out_dir / 'external_validation_results.json'}")
    print()
    print("REMINDER: do not report numerical-threshold detection accuracy on")
    print("eICU. There is no independent label source for it; generating one")
    print("from our own rules would be circular. Say so explicitly.")


if __name__ == "__main__":
    main()
