# PART 3 — boundary density shift  (practical meaning of the guarantee)
# ============================================================================

def part3_boundaries(out_dir, pat, lab, rules):
    print("=" * 74)
    print("PART 3 — LAB DISTRIBUTION & BOUNDARY-DENSITY SHIFT")
    print("=" * 74)
    print("  A3 showed C is a step function: all decision risk sits at thresholds.")
    print("  So a shift in how many orders land NEAR a threshold IS a shift in")
    print("  practical risk, even when the guarantee's algebra is unchanged.")
    print()

    thresholds = defaultdict(set)
    for r in rules:
        canon = cov20.canon_lab(r.get("lab_name") or "")
        t = r.get("threshold")
        if canon and t is not None:
            try:
                thresholds[canon].add(float(t))
            except (TypeError, ValueError):
                pass

    L = lab.merge(pat[["patientunitstayid", "hospitalid"]],
                  on="patientunitstayid", how="left")

    out = {}
    for canon, ts in sorted(thresholds.items()):
        sub = L[L["lab"] == canon]
        if sub.empty:
            print(f"  {canon:<16} NOT PRESENT in eICU under mapped names -- "
                  f"rules on this lab are unevaluable externally")
            out[canon] = {"present": False}
            continue
        v = sub["labresult"].astype(float)
        near = np.zeros(len(v), dtype=bool)
        for t in ts:
            near |= (np.abs(v - t) <= 0.10 * abs(t)) if t else near
        frac = float(near.mean())
        print(f"  {canon:<16} n={len(v):>9,}  median={v.median():>8.2f}  "
              f"thresholds={sorted(ts)}  within10%={frac:.2%}")

        ph = (sub.assign(near=near).groupby("hospitalid")["near"]
              .agg(["size", "mean"]))
        ph = ph[ph["size"] >= 100]
        out[canon] = {
            "present": True, "n": int(len(v)), "median": round(float(v.median()), 4),
            "frac_near_threshold": round(frac, 6),
            "per_hosp_min": round(float(ph["mean"].min()), 6) if len(ph) else None,
            "per_hosp_max": round(float(ph["mean"].max()), 6) if len(ph) else None,
        }
        if len(ph):
            print(f"                   per-hospital near-threshold rate: "
                  f"{ph['mean'].min():.2%} .. {ph['mean'].max():.2%}")
    print()
    print("  Compare `median` against your MIMIC-IV values. Divergence here is")
    print("  the concrete form of 'different lab reference ranges'.")
    print()
    return out


